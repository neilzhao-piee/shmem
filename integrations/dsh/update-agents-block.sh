#!/bin/bash
# DSH integration: regenerate the auto-injected block inside the DSH AGENTS.md file.
#
# Why this exists: the only file that enters a DSH agent's context automatically in
# every session is AGENTS.md itself. So a small "here is what happened elsewhere"
# block is maintained inside AGENTS.md between marker comments — the hand-written
# instructions above the markers are never touched.
#
# Run it after each summarize run (see units/shmem-summarize.service ExecStartPost).
set -uo pipefail
export TZ="${SHMEM_TZ:-UTC}"

ROOT="${SHMEM_ROOT:-.}"
AGENTS="${DSH_AGENTS_MD:-$HOME/.dsh/AGENTS.md}"
MARK_BEGIN='<!-- BEGIN AUTO-INJECTED (shmem-summarizer) -->'
MARK_END='<!-- END AUTO-INJECTED (shmem-summarizer) -->'

journals=$(ls -1 "$ROOT"/journal/*.md 2>/dev/null | sort)
[ -n "$journals" ] || exit 0
journal=$(printf '%s\n' "$journals" | tail -1)   # newest file: drives "recent activity"

# Snapshot lookup walks newest -> oldest: private-memory snapshots are appended only
# when an agent's memory file changes, so a fresh month's journal may not have one yet.
# A real snapshot from the previous journal beats the "(no snapshot yet)" placeholder;
# the placeholder is used only when no journal file holds any snapshot.
#
# The slice keeps the opening of every memory entry, not only the first two: stale
# facts tend to hide further down the list, and an entry that never reaches AGENTS.md
# is invisible to the agent reading it. The "§" separator lines are dropped (they cost
# a line each) and each entry is clipped, so the slice stays a pointer, not a copy.
snap=""
while IFS= read -r f; do
  snap=$(awk '
    /^## .*private memory snapshot/ { block = $0; keep = 1; fence = 0; next }
    keep && fence >= 2 { keep = 0 }
    keep && /^## / { keep = 0 }
    keep {
      block = block "\n" $0
      if ($0 ~ /^```/) fence++
    }
    END { print block }
  ' "$f" | awk 'NF' | awk '$0 != "§" && $0 !~ /^```/' | cut -c1-140 | head -12)
  [ -n "$snap" ] && break
done < <(printf '%s\n' "$journals" | sort -r)
recent=$(awk '
  { lines[NR] = $0 }
  /^### auto-summary/ { hdr[NR] = 1 }
  END {
    c = 0
    for (i = NR; i >= 1 && c < 3; i--) if (hdr[i]) order[++c] = i
    for (j = c; j >= 1; j--) {
      i = order[j]
      print lines[i]
      for (k = i + 1; k <= NR; k++) if (lines[k] != "") { print lines[k]; break }
    }
  }
' "$journal")

# Pipeline health on the surface: the summariser once ran on a dead model for a
# month and every downstream artifact looked normal. Agents reading this file (or
# the workspace mirror below) should see the breakage without reading any logs.
health=$(SHMEM_ROOT="$ROOT" python3 "$ROOT/tools/health-check.py" --oneline 2>/dev/null || true)

tmp=$(mktemp)
{
  echo "$MARK_BEGIN"
  echo
  echo "## Auto-injected shmem block (generated $(date '+%F %H:%M %Z'); full details in $ROOT/INDEX.md and facts/)"
  echo
  echo "### Other agents' memory (latest snapshot)"
  printf '%s\n' "${snap:-"(no snapshot yet)"}"
  echo
  echo "### Recent activity"
  printf '%s\n' "${recent:-"(no auto-summary yet)"}"
  echo
  echo "### Pipeline health"
  printf '%s\n' "${health:-(health check unavailable)}"
  echo "$MARK_END"
} > "$tmp"

[ -r "$AGENTS" ] || : > "$AGENTS"

if grep -qF "$MARK_BEGIN" "$AGENTS"; then
  awk -v b="$MARK_BEGIN" -v e="$MARK_END" -v f="$tmp" '
    $0 == b { while ((getline line < f) > 0) print line; skip = 1; next }
    $0 == e { skip = 0; next }
    !skip { print }
  ' "$AGENTS" > "${AGENTS}.new"
else
  { cat "$AGENTS"; echo; cat "$tmp"; } > "${AGENTS}.new"
fi

mv "${AGENTS}.new" "$AGENTS"
rm -f "$tmp"
echo "AGENTS.md: $(wc -c < "$AGENTS") bytes"

# ---- workspace mirror (SHMEM_MIRROR_MD) ------------------------------------------
# user-global AGENTS.md injection had a regression (.scratch/dsh-user-global-agents-injection),
# so the shared-memory protocol must also live in a workspace AGENTS.md, which is
# injected for sure. A hand-kept mirror drifts (stale timer times, missing facts
# files), so this script maintains the region between its own markers. Hand-written
# Opt out permanently: put a line containing ONLY `shmem-mirror: disabled` in the
# mirror file (anchored — prose that merely MENTIONS the sentinel must not disable it).
MIRROR="${SHMEM_MIRROR_MD:-}"
MMARK_BEGIN='<!-- BEGIN SHMEM MIRROR (auto-generated by update-agents-block.sh) -->'
MMARK_END='<!-- END SHMEM MIRROR (auto-generated by update-agents-block.sh) -->'
if [ -n "$MIRROR" ] && [ -e "$MIRROR" ] && ! grep -qE '^[[:space:]]*shmem-mirror:[[:space:]]*disabled[[:space:]]*$' "$MIRROR"; then
  mtmp=$(mktemp)
  {
    echo "$MMARK_BEGIN"
    echo "## 共享记忆（协议镜像，由 shmem update-agents-block.sh 自动维护）"
    echo
    echo "> user-global \`~/.dsh/AGENTS.md\` 的注入回归未修（票 .scratch/dsh-user-global-agents-injection/），本节是其镜像；修复后删除本节即可（或在本文件单独一行写 shmem-mirror: disabled 停止维护）。"
    echo
    echo '- 入口 `/root/shared-memory/INDEX.md`（`facts/`=当前事实、`journal/`=事件、`inbox/`=消息；`MEMORY.md` 只是存根，别再写它）。开始实质性任务前先读 `INDEX.md`，再按需读对应主题文件（`facts/` 已按主题拆分：fleet=机器索引表+指针、`machines/`=一机一文件、infra / network / models / imagegen / services / crm / agents / spoke…）。查某台机器 → 直接读 `facts/machines/<机器>.md` 或检索，别在 fleet.md 里找详情。'
    echo '- 快速了解近况读 `/root/shared-memory/DIGEST.md`（每日 ~05:30-05:40 AWST 随 summarizer 再生；其第 2 行是流水线健康行，出现 WARN/FAIL 先告知用户再决定是否继续依赖摘要）。'
    echo '- 查旧事用检索，别整篇读 journal：`SHMEM_ROOT=/root/shared-memory python3 /root/shared-memory/tools/memory-search.py "查询词" -n 8`（中文可查，返回文件+行号；markdown 是权威，`.index/memory.db` 可重建；查不到就明说，不要编）。'
    echo '- 三条写入通道：事实变了→原地改 `facts/<主题>.md`；今天发生了什么→`flock -x /root/shared-memory/.lock` 后追加 `journal/<YYYY-MM>.md`；要通知 hermes→写 `inbox/TO-hermes.md`（≤20 行，结论+指针+要它做什么）。'
    echo '- 只写持久事实，带日期和来源（提交号/路径/脚本）；过时内容直接改或删；**密钥/密码绝不入共享记忆**，只写位置。'
    echo '- hermes 私有记忆（`/root/.hermes/memories/`）是冻结注入，共享文件不会自动进它上下文。更多规则在 `~/.dsh/AGENTS.md`（当前注入回归中，需主动读）。'
    echo
    echo "### 近况（auto，$(date '+%F %H:%M %Z')）"
    printf '%s\n' "${recent:-(no auto-summary yet)}"
    echo
    echo '### 流水线健康（auto）'
    printf '%s\n' "${health:-(health check unavailable)}"
    echo "$MMARK_END"
  } > "$mtmp"
  if grep -qF "$MMARK_BEGIN" "$MIRROR"; then
    awk -v b="$MMARK_BEGIN" -v e="$MMARK_END" -v f="$mtmp" '
      $0 == b { while ((getline line < f) > 0) print line; skip = 1; next }
      $0 == e { skip = 0; next }
      !skip { print }
    ' "$MIRROR" > "${MIRROR}.new"
  else
    { cat "$MIRROR"; echo; cat "$mtmp"; } > "${MIRROR}.new"
  fi
  mv "${MIRROR}.new" "$MIRROR"
  rm -f "$mtmp"
  echo "mirror: $MIRROR $(wc -c < "$MIRROR") bytes"
fi
