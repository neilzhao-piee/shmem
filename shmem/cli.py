"""Console entry point for an installed distribution: ``shmem <subcommand>``.

The git-clone workflow stays the front door — ``tools/`` scripts, the Makefile
and the systemd units are what the memory tree itself uses. This CLI is the
extra door for someone who ran ``pip install shmem``: same code, same
``SHMEM_ROOT``, no daemon, no database server.
"""
import subprocess
import sys
from pathlib import Path

from . import get_version

HELP = """shmem — shared memory for agents (markdown + sqlite index, no server)

Set SHMEM_ROOT to your memory tree, then:

  shmem search <query> [-n N] [--json] [--vector]   query-time recall (BM25 + optional vector)
  shmem index [--full]                              re-index what changed
  shmem stats                                       index size + stalled inbox deliveries
  shmem serve [--mcp] [--allow-write]               stdio MCP server (read-only by default)
  shmem summarize                                   LLM/keyword session summarizer
  shmem digest                                      regenerate DIGEST.md (shell tool)
  shmem version
"""


def _digest():
    """DIGEST.md is generated by a shell script; ship it as the script, not a rewrite."""
    root = Path(__file__).resolve().parent.parent
    for candidate in (Path.cwd() / "tools" / "make-digest.sh", root / "tools" / "make-digest.sh"):
        if candidate.is_file():
            return subprocess.run(["bash", str(candidate)]).returncode
    sys.stderr.write("shmem: DIGEST.md is generated by tools/make-digest.sh, which comes from a git "
                     "clone (or 'make digest'). See units/README.md for running it on a schedule.\n")
    return 1


def main(argv=None):
    argv = list(sys.argv[1:] if argv is None else argv)
    if not argv or argv[0] in ("-h", "--help", "help"):
        sys.stdout.write(HELP)
        return 0 if argv else 2
    cmd, rest = argv[0], argv[1:]
    if cmd in ("version", "--version", "-V"):
        sys.stdout.write(get_version() + "\n")
        return 0
    from . import search
    if cmd == "search":
        return search.main(rest) or 0
    if cmd == "index":
        return search.main(["--rebuild"] + rest) or 0
    if cmd == "stats":
        return search.main(["--stats"] + rest) or 0
    if cmd == "serve":
        return search.main(["--mcp"] + rest) or 0
    if cmd == "summarize":
        from . import summarize
        return summarize.main() or 0
    if cmd == "digest":
        return _digest()
    sys.stderr.write(f"shmem: unknown subcommand {cmd!r}\n\n{HELP}")
    return 2


if __name__ == "__main__":
    sys.exit(main())
