#!/bin/bash
# Regenerate DIGEST.md in the shmem root: a single self-contained snapshot that
# works for file-capable agents (read it) AND for sandboxed agents (upload/paste it).
# Requires GNU coreutils (tac).
set -uo pipefail
export TZ="${SHMEM_TZ:-UTC}"
ROOT="${SHMEM_ROOT:-.}"
cd "$ROOT" || exit 1

[ -r INDEX.md ] || { echo "no INDEX.md in $ROOT" >&2; exit 1; }

tmp=$(mktemp)
{
  echo "# shmem digest (auto-generated: $(date '+%F %H:%M %Z'))"
  echo
  echo "> Generated by tools/make-digest.sh. An agent that cannot read local files (e.g. a sandboxed browser agent) can paste or upload this file instead."
  echo
  sed -n '1,60p' INDEX.md
  echo
  echo "## Current facts (sketch)"
  for f in facts/*.md; do
    [ -r "$f" ] || continue
    echo
    echo "### ${f#facts/}"
    awk 'NF' "$f" | head -n 8
  done
  echo
  echo "## Recent activity (auto-summary, newest first)"
  for f in journal/*.md; do
    [ -r "$f" ] || continue
    tac "$f" | awk '/^### auto-summary/{c++} c<6' | tac | head -c 1500
  done
  echo
  echo "## Private memory snapshots (most recent)"
  for f in journal/*.md; do
    [ -r "$f" ] || continue
    awk '/^## .*private memory snapshot/{block=$0; keep=1; next} keep{block=block"\n"$0} END{print block}' "$f" | head -c 1000
  done
} > "$tmp" 2>/dev/null

head -c 9000 "$tmp" > DIGEST.md
rm -f "$tmp"
echo "digest: $(wc -c < DIGEST.md) bytes"
