#!/bin/bash
# Regenerate DIGEST.md in the shmem root: a single self-contained snapshot that
# works for file-capable agents (read it) AND for sandboxed agents (upload/paste it).
set -uo pipefail
export TZ="${SHMEM_TZ:-UTC}"
ROOT="${SHMEM_ROOT:-.}"
cd "$ROOT" || exit 1

[ -r INDEX.md ] || { echo "no INDEX.md in $ROOT" >&2; exit 1; }

sec_hdr=$(mktemp); sec_head=$(mktemp); sec_act=$(mktemp); sec_snap=$(mktemp)
{
  echo "# shmem digest (auto-generated: $(date '+%F %H:%M %Z'))"
  echo
  echo "> Generated by tools/make-digest.sh. An agent that cannot read local files (e.g. a sandboxed browser agent) can paste or upload this file instead."
  # Pipeline health on the surface: the summariser ran on a dead model for a month
  # while everything downstream looked normal. One line here makes that visible in
  # every injected/pasted copy of the digest, not just to whoever reads .summarize.log.
  health=$(SHMEM_ROOT="$ROOT" python3 "$ROOT/tools/health-check.py" --oneline 2>/dev/null || true)
  [ -n "$health" ] && { echo "> $health"; }
  echo
} > "$sec_hdr"
{
  # Structure slice only (tree + per-file descriptions = the file-level TOC). The
  # protocol prose below that marker lives in the full INDEX.md and in the injected
  # AGENTS block — the digest must fit real content in its 9KB, not duplicate it.
  sed -n '1,/^## 检索层/p' INDEX.md | sed '$d' | head -n 60
  echo
  echo "## Facts section map (which ## is where)"
  # machines/ is one-file-per-machine: the names ARE the section info (fleet.md
  # holds the index table). Printed FIRST: per-file "###" entries were
  # alphabetically cut by head_budget, and a collapsed line must survive the cap.
  if [ -d facts/machines ]; then
    echo
    echo "### machines/ — 一机一文件（索引表在 fleet.md「机器」节）："
    (cd facts/machines && ls *.md 2>/dev/null | sed 's/\.md$//' | paste -sd ' ' - | sed 's/^/  /')
  fi
  for f in $(find facts -maxdepth 1 -name '*.md' | sort); do
    [ -r "$f" ] || continue
    echo
    echo "### ${f#facts/}"
    # Demote to list items: raw "## " lines would become DIGEST's own section
    # headings and defeat every TOC built from '^## '.
    grep '^## ' "$f" | sed 's/^## /  - /' | head -n 4
  done
} > "$sec_head" 2>/dev/null
{
  echo "## Recent activity (auto-summary, newest first)"
  # Newest journal file first, 5 blocks total across files — the old loop took 5 per
  # file, so a previous month could crowd out the newest activity.
  need=5
  for f in $(ls -1 journal/*.md 2>/dev/null | sort -r); do
    [ "$need" -gt 0 ] || break
    total=$(grep -c '^### auto-summary' "$f" || true)
    [ "$total" -gt 0 ] || continue
    take=$(( total < need ? total : need ))
    awk -v k="$take" '
      /^#/ { cur = ($0 ~ /^### auto-summary/) ? ++n : 0 }
      cur { b[cur] = (cur in b ? b[cur] "\n" : "") $0 }
      END { s = (n > k) ? n - k + 1 : 1; for (i = s; i <= n; i++) print b[i] }
    ' "$f"
    need=$(( need - take ))
  done
} > "$sec_act" 2>/dev/null
{
  echo "## Private memory snapshots (most recent)"
  # The newest snapshot across all journals (newest file first) — the same fallback
  # semantics as the injected block, not every file's trailing block.
  for f in $(ls -1 journal/*.md 2>/dev/null | sort -r); do
    grep -q '^## .*private memory snapshot' "$f" || continue
    awk '
      /^## / { cur = ($0 ~ /private memory snapshot/) ? ++n : 0 }
      cur { b[cur] = (cur in b ? b[cur] "\n" : "") $0 }
      END { if (n) print b[n] }
    ' "$f"
    break
  done
} > "$sec_snap" 2>/dev/null

# Section budgets: the index+facts head used to consume the whole 9KB, silently
# cutting activity and snapshots (a real memory tree's INDEX alone can be 6KB+).
# Reserve the tail sections first, then give the head whatever budget remains.
# All cuts are at line boundaries (LC_ALL=C => length() counts bytes).
cap_lines() { LC_ALL=C awk -v max="$1" 'BEGIN{n=0} {b=length($0)+1; if(n+b>max) exit; n+=b; print}' "$2"; }
cap_lines 1800 "$sec_act" > "${sec_act}.c" && mv "${sec_act}.c" "$sec_act"
cap_lines 2200 "$sec_snap" > "${sec_snap}.c" && mv "${sec_snap}.c" "$sec_snap"
head_budget=$(( 9000 - $(wc -c < "$sec_hdr") - $(wc -c < "$sec_act") - $(wc -c < "$sec_snap") ))
{
  cat "$sec_hdr"
  cap_lines "$head_budget" "$sec_head"
  echo
  cat "$sec_act"
  echo
  cat "$sec_snap"
} > DIGEST.md
rm -f "$sec_hdr" "$sec_head" "$sec_act" "$sec_snap"
echo "digest: $(wc -c < DIGEST.md) bytes"
